const FAMILY_FALLBACKS: Array<[RegExp, string]> = [
  [/^PFI/, "PFI2502000"],
  [/^PFT/, "PFT2502000"],
  [/^PMI/, "PMI2502000"],
  [/^PMT/, "PMT2502000"],
  [/^PMAM/, "PMAM10002000"],
  [/^PORTMOT/, "PORTMOT100030003000"],
  [/^PORTI/, "PORTI2502000H1"],
  [/^PORT/, "PORT500080004500"],
  [/^PRT/, "PRT1502000"],
];

export const PRODUCT_IMAGE_FALLBACK = "/images/hero-potence.png";

export function normalizeProductImageRef(reference?: string | null) {
  if (!reference) return undefined;

  const normalized = reference
    .toUpperCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/KG/g, "")
    .replace(/MM/g, "")
    .replace(/[^A-Z0-9]/g, "");

  return normalized || undefined;
}

export function getProductImageUrl(...references: Array<string | undefined | null>) {
  const importedImage = getImportedProductMainImage(...references);
  if (importedImage) return importedImage;

  const normalizedRefs = references
    .map((reference) => normalizeProductImageRef(reference))
    .filter((reference): reference is string => Boolean(reference));

  for (const reference of normalizedRefs) {
    if (PRODUCT_IMAGE_REFS.has(reference)) {
      return `/images/products/${reference}.webp`;
    }
  }

  for (const reference of normalizedRefs) {
    const fallback = FAMILY_FALLBACKS.find(([pattern, imageRef]) => pattern.test(reference) && PRODUCT_IMAGE_REFS.has(imageRef));
    if (fallback) {
      return `/images/products/${fallback[1]}.webp`;
    }
  }

  return PRODUCT_IMAGE_FALLBACK;
}

export function hasProductImage(reference?: string | null) {
  const normalized = normalizeProductImageRef(reference);
  return Boolean(normalized && PRODUCT_IMAGE_REFS.has(normalized));
}
